// Functions

// Get column of a 2D array
void get_column(size_t M, const double (*row)[M][4], size_t col_idx, double *out) {
	for (size_t i = 0; i < M; ++i) {
		out[i] = *row[i][col_idx];
	}
}


// Inner product of two arrays length n
double inner_product(size_t n, const double (*A)[n], const double (*B)[n]) {
	double sum = 0.0;
	for (size_t i = 0; i < n; i++) {
		sum += (*A)[i] * (*B)[i];
	}

	return sum;
}


// Constructs the final values given the set of values
// NOTE: Only used for R_values, L_values, and B_values
// double *T[N][M][4]
double constructValue(size_t N, size_t M, const double (*T)[N][M][4], double jd) {
	// Don't need the entire algorithms.cpp file here...
	const double curr_JME = (jd - J2000) / 36525.0;
	double T_sums[N] = {};

	// TODO: ++n or n++? Was originally ++n
	for (size_t n = 0; n < N; ++n) {
		for (size_t i = 0; i < M; ++i) {
			double A[M] = {};
			double B[M] = {};
			double C[M] = {};

			get_column(M, &(*T)[n], 1, A); // 2nd col
			get_column(M, &(*T)[n], 2, B);
			get_column(M, &(*T)[n], 3, C);

			// Apply cos to each B[i] + C[i] * curr_JME
			double cos_B_C[M] = {};
			for (size_t i = 0; i < M; ++i) {
				cos_B_C[i] = cos(B[i] + C[i] * curr_JME);
			}

			// Calculate inner product of A and cos_B_C for this M
			T_sums[n] += inner_product(M, &A, &cos_B_C);
		}
	}
	// Uncomment the return statement to complete the function
	double T_total = 0.0;
	for (size_t i = 0; i < sizeof(T_sums)/sizeof(T_sums[0]); i++) {
		T_total += T_sums[i];
	}
	// return pow(10, -8) * accumulate(T_sums, T_sums + N, 0.0);
	return pow(10, -8) * T_total;
}
